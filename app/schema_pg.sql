-- Postgres version of schema.sql, used when DATABASE_URL is set (hosted deployments).
CREATE TABLE IF NOT EXISTS trainees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    callsign TEXT NOT NULL,
    unit TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    UNIQUE (callsign, unit)
);

CREATE TABLE IF NOT EXISTS sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainee_id BIGINT NOT NULL REFERENCES trainees (id),
    scenario_id TEXT NOT NULL,
    scenario_name TEXT NOT NULL,
    seed BIGINT NOT NULL,
    params TEXT,
    started_at TEXT NOT NULL,
    duration_s DOUBLE PRECISION NOT NULL,
    total DOUBLE PRECISION NOT NULL,
    detection DOUBLE PRECISION NOT NULL,
    classification DOUBLE PRECISION NOT NULL,
    engagement DOUBLE PRECISION NOT NULL,
    grade TEXT NOT NULL,
    false_alarms INTEGER NOT NULL,
    breaches INTEGER NOT NULL,
    critical_errors INTEGER NOT NULL,
    result TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES sessions (id) ON DELETE CASCADE,
    t DOUBLE PRECISION NOT NULL,
    type TEXT NOT NULL,
    contact_id TEXT,
    data TEXT
);

CREATE INDEX IF NOT EXISTS idx_sessions_trainee ON sessions (trainee_id, started_at);
CREATE INDEX IF NOT EXISTS idx_events_session ON events (session_id, t);
